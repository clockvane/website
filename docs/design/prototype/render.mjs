// Build-time only. The generated HTML has no scripts or runtime dependencies.
import { readFile, writeFile } from 'node:fs/promises';
import { siteConfig } from '../../../site.config.ts';

const here = new URL('./', import.meta.url);
const tokens = JSON.parse(
  await readFile(new URL('../tokens.json', here), 'utf8'),
);
const copy = await readFile(
  new URL('../../content/copy-deck.md', here),
  'utf8',
);
const template = await readFile(new URL('index.template.html', here), 'utf8');
const escape = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (c) =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[
        c
      ],
  );
const lookup = (path) =>
  path.split('.').reduce((node, key) => node[key], tokens);
const name = (path) =>
  path.replaceAll('.', '-').replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
function value(token) {
  const v = token.$value;
  if (typeof v === 'string' && v.startsWith('{'))
    return `var(--${name(v.slice(1, -1))})`;
  if (v?.colorSpace) return v.hex;
  if (v?.unit) return `${v.value}${v.unit}`;
  if (Array.isArray(v))
    return typeof v[0] === 'number'
      ? `cubic-bezier(${v.join(', ')})`
      : v
          .map((family) =>
            family.includes(' ') ? JSON.stringify(family) : family,
          )
          .join(', ');
  if (typeof v === 'object') return null; // Unused flat-shadow composite; no shadow in the prototype.
  return String(v);
}
function properties(group, path = '') {
  return Object.entries(group).flatMap(([key, token]) => {
    if (key.startsWith('$')) return [];
    const next = path ? `${path}.${key}` : key;
    if ('$value' in token)
      return value(token) === null ? [] : [`--${name(next)}: ${value(token)};`];
    return properties(token, next);
  });
}
const serviceTable = copy
  .split('### Service names (single source)')[1]
  .split('\n---')[0];
const services = [
  ...serviceTable.matchAll(/^\| `([^`]+)` \| ([^|]+) \| ([^|]+) \|$/gm),
].map(([, slug, title, summary]) => ({
  slug,
  title: title.trim(),
  summary: summary.trim(),
}));
if (services.length !== 5)
  throw new Error(
    'Review service-table changes before regenerating the prototype.',
  );
const link = ({ slug, title }) =>
  `<li><a class="standalone" href="#preview-${escape(slug)}">${escape(title)}</a></li>`;
const connector =
  '<svg class="connector" viewBox="0 0 20 40" aria-hidden="true" focusable="false"><path d="M10 0V40 M6 34L10 39L14 34"/></svg>';
const person =
  '<svg class="person" viewBox="0 0 20 20" aria-hidden="true" focusable="false"><circle cx="10" cy="5" r="3"/><path d="M3 18Q3 10 10 10Q17 10 17 18"/></svg>';
const pipeline = (manual) =>
  ['Shop', 'Spreadsheet', 'Invoice tool']
    .map(
      (label, i) =>
        `<li><span class="node">${manual ? person : ''}${label}</span>${i < 2 ? connector : ''}</li>`,
    )
    .join('');
const replacements = {
  'brand.name': escape(siteConfig.brand),
  year: String(new Date().getUTCFullYear()),
  tokens: properties(tokens).join('\n'),
  'services.links': services.map(link).join('\n'),
  'services.rows': services
    .map(
      ({ slug, title, summary }) =>
        `<article class="service-row"><h3>${escape(title)}</h3><div><p>${escape(summary)}</p><a class="standalone" href="#preview-${escape(slug)}">Read about ${escape(title)}</a></div></article>`,
    )
    .join('\n'),
  'services.destinations': services
    .map(
      ({ slug, title }) =>
        `<section class="prototype-note" id="preview-${escape(slug)}" tabindex="-1"><h2>DRAFT · ${escape(title)}</h2><p>Destination: /services/${escape(slug)}/. This offline prototype shows only the home page.</p><a class="standalone" href="#services">Back to services</a></section>`,
    )
    .join('\n'),
  'diagram.before': pipeline(true),
  'diagram.after': pipeline(false),
};
const output = template.replace(/\{\{([^}]+)\}\}/g, (_, key) => {
  const result = replacements[key] ?? value(lookup(key));
  if (!result) throw new Error(`Missing template value: ${key}`);
  return result;
});
await writeFile(
  new URL('index.html', here),
  `<!-- Generated by render.mjs from the template, tokens, copy deck and site.config.ts. -->\n${output}`,
);
