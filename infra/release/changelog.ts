// Changelog generator (docs/devops/release.md). No dependencies, no server.
// Usage: node infra/release/changelog.ts --version 1.2.0 [--from v1.1.0] [--to HEAD] [--date YYYY-MM-DD] [--write]
// Squash-merge subjects on main are Conventional Commits; they become the entries.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

export type Entry = {
  type: string;
  scope: string;
  text: string;
  breaking: boolean;
  ref: string;
};

const SECTIONS: [string, string][] = [
  ['feat', 'Added'],
  ['fix', 'Fixed'],
  ['perf', 'Changed'],
];
const PATTERN =
  /^(\w+)(?:\(([^)]+)\))?(!)?: (.+?)(?: \(#(\d+)\))?(?: \(#(\d+)\))?$/;

export function parseSubject(subject: string): Entry | null {
  const m = PATTERN.exec(subject.trim());
  if (!m) return null;
  return {
    type: m[1] ?? '',
    scope: m[2] ?? '',
    breaking: m[3] === '!',
    text: m[4] ?? '',
    // Titles may carry the issue number and then the PR number; the PR number comes last.
    ref: m[6] ?? m[5] ?? '',
  };
}

function line(e: Entry): string {
  const scope = e.scope ? `**${e.scope}:** ` : '';
  return `- ${scope}${e.text}${e.ref ? ` (#${e.ref})` : ''}`;
}

export function renderSection(
  version: string,
  date: string,
  subjects: string[],
): string {
  const entries = subjects
    .map(parseSubject)
    .filter((e): e is Entry => e !== null);
  const out = [`## [${version}] - ${date}`];
  const breaking = entries.filter((e) => e.breaking);
  const groups: [string, Entry[]][] = [['Breaking changes', breaking]];
  for (const [type, title] of SECTIONS) {
    groups.push([title, entries.filter((e) => e.type === type && !e.breaking)]);
  }
  // Hidden types (docs, ci, chore, test, refactor) appear only when marked breaking.
  let any = false;
  for (const [title, list] of groups) {
    if (list.length === 0) continue;
    any = true;
    out.push('', `### ${title}`, ...list.map(line));
  }
  if (!any) out.push('', '- Maintenance only; no user-visible changes.');
  return `${out.join('\n')}\n`;
}

const HEADER =
  '# Changelog\n\nAll notable changes to this project are documented here. Format: Keep a Changelog; versions: SemVer.\nGenerated by `infra/release/changelog.ts` from Conventional Commit titles.\n';

export function prepend(existing: string, section: string): string {
  const body = existing.startsWith('# Changelog')
    ? existing.slice(
        existing.indexOf('\n## ') === -1
          ? existing.length
          : existing.indexOf('\n## ') + 1,
      )
    : existing;
  return `${HEADER}\n${section}${body ? `\n${body.replace(/^\n+/, '')}` : ''}`;
}

function arg(name: string, fallback = ''): string {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? fallback : (process.argv[i + 1] ?? fallback);
}

function main(): void {
  const version = arg('version');
  if (!/^\d+\.\d+\.\d+$/.test(version))
    throw new Error('--version X.Y.Z is required');
  const from = arg('from');
  const to = arg('to', 'HEAD');
  for (const ref of [from, to]) {
    if (ref && !/^[\w./-]+$/.test(ref)) throw new Error(`bad ref: ${ref}`);
  }
  const range = from ? `${from}..${to}` : to;
  const log = execFileSync(
    'git',
    ['log', '--first-parent', '--format=%s', range],
    { encoding: 'utf8' },
  );
  const date = arg('date', new Date().toISOString().slice(0, 10));
  const section = renderSection(version, date, log.split('\n').filter(Boolean));
  if (process.argv.includes('--write')) {
    const file = 'CHANGELOG.md';
    writeFileSync(
      file,
      prepend(existsSync(file) ? readFileSync(file, 'utf8') : '', section),
    );
  } else {
    process.stdout.write(section);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
